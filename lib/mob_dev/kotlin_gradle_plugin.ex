defmodule MobDev.KotlinGradlePlugin do
  @moduledoc """
  Detects an Android build still on a Kotlin Gradle plugin (KGP) below 2.4.20,
  which has CVE-2026-53914 (GHSA-r937-wjx7-w2jp): code execution through
  unsafe deserialization of Gradle build-cache metadata (MOB-497).

  Apps generated by mob_new before its Kotlin 2 migration pin
  `org.jetbrains.kotlin:kotlin-gradle-plugin:1.9.22`. The Gradle files are
  app-owned, so `mix mob.doctor` reports and never rewrites them (see
  `decisions/2026-08-25-detect-dont-autopatch-native-source.md`).

  Read from the root, settings and app build scripts (Groovy or Kotlin DSL)
  and `gradle/libs.versions.toml`:

    * the `org.jetbrains.kotlin:kotlin-gradle-plugin` coordinate, with a
      literal version, a `$var` resolved from an assignment in the same file,
      or a `strictly`/`require`/`prefer` block;
    * the plugin ids that resolve to that artifact
      (`org.jetbrains.kotlin.android`, `.jvm`, `.multiplatform`, `.kapt`, and
      the `kotlin("…")` shorthand) with a version;
    * catalog `[libraries]` and `[plugins]` entries for either, with
      `version = "…"` or `version.ref` resolved through `[versions]`.

  Only those count. Other Kotlin plugins (serialization, compose), a
  `kotlin` catalog key that nothing above references, and commented-out
  lines are ignored, and a version that can't be resolved to a literal is
  never guessed: doctor only warns, so a false positive would tell a fixed
  app it is still exposed every time it runs.

  AGP 9 compiles Kotlin itself and depends on KGP 2.2.10 at runtime, so an
  AGP 9 build that declares no KGP at all is on 2.2.10 and is reported too.
  """

  @fixed Version.parse!("2.4.20-Beta1")

  @build_files ~w(
    android/build.gradle
    android/build.gradle.kts
    android/settings.gradle
    android/settings.gradle.kts
    android/app/build.gradle
    android/app/build.gradle.kts
  )

  @catalog "android/gradle/libs.versions.toml"

  @kgp %{
    module: "org.jetbrains.kotlin:kotlin-gradle-plugin",
    plugin_ids: ~w(
      org.jetbrains.kotlin.android
      org.jetbrains.kotlin.jvm
      org.jetbrains.kotlin.multiplatform
      org.jetbrains.kotlin.kapt
    ),
    kotlin_shorthand: ~w(android jvm multiplatform kapt)
  }

  @agp %{
    module: "com.android.tools.build:gradle",
    plugin_ids: ~w(com.android.application com.android.library),
    kotlin_shorthand: []
  }

  @typedoc "A reason to warn, with the project-relative file it was read from."
  @type finding ::
          {:vulnerable, Path.t(), [String.t()]}
          | {:builtin_kotlin_unpinned, Path.t(), String.t()}

  @doc """
  The findings for the Android project under `root`, sorted by file. `[]`
  when every declared KGP is at or above 2.4.20 (or there is no Android
  build to read).
  """
  @spec check(Path.t()) :: [finding()]
  def check(root) do
    sources =
      for rel <- [@catalog | @build_files],
          {:ok, content} <- [File.read(Path.join(root, rel))],
          do: {rel, strip_comments(rel, content)}

    kgp = Enum.map(sources, fn {rel, content} -> {rel, declared(rel, content, @kgp)} end)

    vulnerable =
      for {rel, decls} <- kgp,
          stale <- [decls |> literal_versions() |> Enum.filter(&below_fix?/1)],
          stale != [],
          do: {:vulnerable, rel, stale}

    cond do
      vulnerable != [] ->
        Enum.sort(vulnerable)

      Enum.all?(kgp, fn {_rel, decls} -> decls == [] end) ->
        builtin_kotlin_unpinned(sources)

      true ->
        []
    end
  end

  @doc "True when `version` is a parseable version below the CVE-2026-53914 fix."
  @spec below_fix?(String.t()) :: boolean()
  def below_fix?(version) do
    case Version.parse(version) do
      {:ok, v} -> Version.compare(v, @fixed) == :lt
      :error -> false
    end
  end

  defp builtin_kotlin_unpinned(sources) do
    Enum.find_value(sources, [], fn {rel, content} ->
      agp_9 =
        rel
        |> declared(content, @agp)
        |> literal_versions()
        |> Enum.find(&(major(&1) >= 9))

      if agp_9, do: [{:builtin_kotlin_unpinned, rel, agp_9}]
    end)
  end

  defp major(version) do
    case Integer.parse(version) do
      {n, _} -> n
      :error -> 0
    end
  end

  defp literal_versions(decls), do: for({:version, v} <- decls, uniq: true, do: v)

  # ── Comment stripping ─────────────────────────────────────────────────────

  defp strip_comments(@catalog, content),
    do: Regex.replace(Regex.compile!("(?m)#.*$"), content, "")

  # `(?<!:)` keeps `https://…` URLs intact.
  defp strip_comments(_build_file, content) do
    content = Regex.replace(Regex.compile!("(?s)/\\*.*?\\*/"), content, "")
    Regex.replace(Regex.compile!("(?m)(?<!:)//.*$"), content, "")
  end

  # ── Build scripts ─────────────────────────────────────────────────────────

  # Each declaration is `{:version, literal}` or `:unresolved` (a variable
  # this file doesn't assign) — the latter still means the build declares
  # the artifact, so it is not "unpinned".
  defp declared(@catalog, content, spec), do: catalog_declared(content, spec)

  defp declared(_build_file, content, spec) do
    vars = assignments(content)
    module = Regex.escape(spec.module)
    ids = Enum.map_join(spec.plugin_ids, "|", &Regex.escape/1)

    patterns =
      [
        # classpath 'g:a:1.2.3' / "g:a:$v" / ("g:a:${v}")
        "#{module}:([^'\"\\s)]+)",
        # classpath("g:a") { version { strictly("1.2.3") } }
        "#{module}['\"]\\s*\\)?\\s*\\{[^}]*?(?:strictly|require|prefer)\\s*\\(?\\s*['\"]([^'\"]+)",
        # id 'x' version '1' / id("x") version "1" / id("x").version("1")
        "id\\s*\\(?\\s*['\"](?:#{ids})['\"]\\s*\\)?\\s*\\.?\\s*version\\s*\\(?\\s*['\"]([^'\"]+)"
      ] ++ shorthand_pattern(spec)

    # A versionless `classpath("g:a")` (version from a BOM, a catalog or a
    # strictly block) still declares the artifact.
    versionless =
      for _ <- Regex.scan(Regex.compile!("#{module}['\"]"), content), do: :unresolved

    versionless ++
      Enum.flat_map(patterns, fn pattern ->
        pattern
        |> Regex.compile!()
        |> Regex.scan(content, capture: :all_but_first)
        |> Enum.map(fn [raw] -> resolve(raw, vars) end)
      end)
  end

  defp shorthand_pattern(%{kotlin_shorthand: []}), do: []

  defp shorthand_pattern(%{kotlin_shorthand: names}) do
    alts = Enum.map_join(names, "|", &Regex.escape/1)
    ["kotlin\\s*\\(\\s*\"(?:#{alts})\"\\s*\\)\\s*\\.?\\s*version\\s*\\(?\\s*\"([^\"]+)"]
  end

  # `ext.kotlin_version = '1.9.22'`, `def v = "…"`, `val v = "…"`,
  # `kotlin_version = '…'` inside an `ext { }` block.
  defp assignments(content) do
    "(?m)^\\s*(?:ext\\.|def\\s+|val\\s+|var\\s+)?(\\w+)\\s*=\\s*['\"]([^'\"$]+)['\"]"
    |> Regex.compile!()
    |> Regex.scan(content, capture: :all_but_first)
    |> Map.new(fn [name, value] -> {name, value} end)
  end

  defp resolve(raw, vars) do
    case Regex.run(Regex.compile!("^\\$\\{?(?:\\w+\\.)*(\\w+)\\}?$"), raw,
           capture: :all_but_first
         ) do
      nil -> {:version, raw}
      [name] -> if v = vars[name], do: {:version, v}, else: :unresolved
    end
  end

  # ── Version catalog ───────────────────────────────────────────────────────

  # TOML inline tables are single-line, so an entry is one line.
  defp catalog_declared(content, spec) do
    sections = catalog_sections(content)
    versions = catalog_versions(Map.get(sections, "versions", []))

    library_lines =
      sections
      |> Map.get("libraries", [])
      |> Enum.filter(&catalog_library?(&1, spec.module))

    plugin_lines =
      sections
      |> Map.get("plugins", [])
      |> Enum.filter(&catalog_plugin?(&1, spec.plugin_ids))

    Enum.flat_map(library_lines, &catalog_version(&1, spec.module, versions)) ++
      Enum.flat_map(plugin_lines, &catalog_plugin_version(&1, spec.plugin_ids, versions))
  end

  defp catalog_sections(content) do
    header = Regex.compile!("^\\s*\\[([\\w.-]+)\\]\\s*$")

    content
    |> String.split("\n")
    |> Enum.reduce({nil, %{}}, fn line, {section, acc} ->
      case Regex.run(header, line, capture: :all_but_first) do
        [name] -> {name, acc}
        nil when is_nil(section) -> {section, acc}
        nil -> {section, Map.update(acc, section, [line], &[line | &1])}
      end
    end)
    |> elem(1)
    |> Map.new(fn {section, lines} -> {section, Enum.reverse(lines)} end)
  end

  # `kotlin = "1.9.22"` or `kotlin = { strictly = "1.9.22" }`.
  defp catalog_versions(lines) do
    entry = Regex.compile!("^\\s*([\\w.-]+)\\s*=\\s*(.+)$")
    literal = Regex.compile!("^\"([^\"]+)\"")
    rich = Regex.compile!("(?:strictly|require|prefer)\\s*=\\s*\"([^\"]+)\"")

    for line <- lines,
        [key, rhs] <- [Regex.run(entry, line, capture: :all_but_first)],
        [value] <- [Regex.run(literal, rhs, capture: :all_but_first) || rich_value(rich, rhs)],
        into: %{},
        do: {key, value}
  end

  defp rich_value(rich, rhs), do: Regex.run(rich, rhs, capture: :all_but_first) || []

  defp catalog_library?(line, module) do
    [group, name] = String.split(module, ":")

    String.contains?(line, "\"#{module}") or
      (String.contains?(line, "\"#{group}\"") and String.contains?(line, "\"#{name}\""))
  end

  defp catalog_plugin?(line, ids) do
    Enum.any?(ids, fn id ->
      String.contains?(line, "\"#{id}\"") or String.contains?(line, "\"#{id}:")
    end)
  end

  # String notation `"g:a:1.2.3"`, else the entry's `version`.
  defp catalog_version(line, module, versions) do
    case Regex.run(Regex.compile!("\"#{Regex.escape(module)}:([^\"]+)\""), line,
           capture: :all_but_first
         ) do
      [v] -> [{:version, v}]
      nil -> catalog_entry_version(line, versions)
    end
  end

  defp catalog_plugin_version(line, ids, versions) do
    alts = Enum.map_join(ids, "|", &Regex.escape/1)

    case Regex.run(Regex.compile!("\"(?:#{alts}):([^\"]+)\""), line, capture: :all_but_first) do
      [v] -> [{:version, v}]
      nil -> catalog_entry_version(line, versions)
    end
  end

  # `version = "1"`, `version = { strictly = "1" }`, `version.ref = "k"`,
  # `version = { ref = "k" }`. No version at all (a library whose version a
  # platform/BOM supplies) declares the artifact without a literal.
  defp catalog_entry_version(line, versions) do
    ref = Regex.compile!("version(?:\\.ref\\s*=|\\s*=\\s*\\{[^}]*\\bref\\s*=)\\s*\"([^\"]+)\"")
    literal = Regex.compile!("version\\s*=\\s*\"([^\"]+)\"")

    rich =
      Regex.compile!("version\\s*=\\s*\\{[^}]*(?:strictly|require|prefer)\\s*=\\s*\"([^\"]+)\"")

    cond do
      match = Regex.run(ref, line, capture: :all_but_first) ->
        [key] = match
        if v = versions[key], do: [{:version, v}], else: [:unresolved]

      match =
          Regex.run(literal, line, capture: :all_but_first) ||
            Regex.run(rich, line, capture: :all_but_first) ->
        [v] = match
        [{:version, v}]

      true ->
        [:unresolved]
    end
  end
end
